import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, readFile, rm, stat } from "node:fs/promises";
import path from "node:path";
import { PassThrough, Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import {
  AbortMultipartUploadCommand,
  CompleteMultipartUploadCommand,
  CreateMultipartUploadCommand,
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
  UploadPartCommand,
} from "@aws-sdk/client-s3";
import { logger } from "../lib/logger";

// Byte storage for campaign delivery media (V2-05B). Keys are generated by
// the server only (never from a request), and every backend refuses a key
// that would leave its root. Selected explicitly with CAMPAIGN_MEDIA_STORAGE
// (R-D2, R1b; validated at startup by index.ts):
//  - "s3": an S3-compatible bucket (MinIO on the dedicated servers, or AWS),
//    configured with CAMPAIGN_MEDIA_S3_*; the production backend;
//  - "local": local disk under CAMPAIGN_MEDIA_STORAGE_DIR, for development
//    and tests only (refused when NODE_ENV is production);
//  - unset: no storage; uploads answer 503 media_storage_unavailable.
// Nothing falls back to a public bucket or a URL. Storage errors carry fixed
// messages: never the endpoint, bucket, key or a credential.

export interface CampaignMediaStore {
  readonly kind: "s3" | "local_disk";
  put(key: string, body: AsyncIterable<Buffer>): Promise<void>;
  read(key: string, maxBytes: number): Promise<Buffer>;
  stream(key: string): Readable;
  remove(key: string): Promise<void>;
}

const KEY_PATTERN = /^organizations\/\d+\/campaigns\/\d+\/media\/[0-9a-f-]{36}$/;

export function assertMediaKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error("Invalid campaign media storage key");
}

export class CampaignMediaStoreError extends Error {
  constructor(readonly code: "not_found" | "too_large" | "unavailable", message: string) {
    super(message);
    this.name = "CampaignMediaStoreError";
  }
}

const TOO_LARGE = "Stored campaign media is larger than allowed";

export class LocalDiskMediaStore implements CampaignMediaStore {
  readonly kind = "local_disk" as const;
  constructor(private readonly root: string) {}

  private file(key: string): string {
    assertMediaKey(key);
    const resolved = path.resolve(this.root, key);
    const relative = path.relative(path.resolve(this.root), resolved);
    if (relative.startsWith("..") || path.isAbsolute(relative)) throw new Error("Campaign media key escapes the storage root");
    return resolved;
  }

  async put(key: string, body: AsyncIterable<Buffer>): Promise<void> {
    const file = this.file(key);
    await mkdir(path.dirname(file), { recursive: true });
    await pipeline(Readable.from(body), createWriteStream(file, { flags: "wx" }));
  }

  async read(key: string, maxBytes: number): Promise<Buffer> {
    const file = this.file(key);
    const info = await stat(file);
    if (info.size > maxBytes) throw new Error(TOO_LARGE);
    return readFile(file);
  }

  stream(key: string): Readable {
    return createReadStream(this.file(key));
  }

  async remove(key: string): Promise<void> {
    await rm(this.file(key), { force: true });
  }
}

/** Smallest part S3 accepts for every part but the last. */
export const S3_MIN_PART_BYTES = 5 * 1024 * 1024;
const DEFAULT_PART_BYTES = 8 * 1024 * 1024;

function storageStatus(error: unknown): { name?: string; status?: number } {
  const record = error as { name?: string; $metadata?: { httpStatusCode?: number } } | undefined;
  return { name: record?.name, status: record?.$metadata?.httpStatusCode };
}

function isMissing(error: unknown): boolean {
  const { name, status } = storageStatus(error);
  return name === "NoSuchKey" || name === "NotFound" || status === 404;
}

/** Wraps an SDK failure into a fixed message; the SDK name and status go to the log only. */
function unavailable(operation: string, error: unknown): CampaignMediaStoreError {
  logger.warn({ storage: "s3", operation, errorName: storageStatus(error).name, httpStatus: storageStatus(error).status }, "campaign media storage request failed");
  return new CampaignMediaStoreError("unavailable", "Campaign media storage is unavailable");
}

/**
 * S3-compatible store (R-D2). Bodies are always sent as Buffers with an explicit length (S3 and MinIO refuse
 * chunked PutObject, and SigV4 then signs the payload hash): a body smaller than one part is one PutObject,
 * anything larger is a sequential multipart upload holding at most one part in memory, aborted on any error.
 * An error raised by the body iterator itself (size or content checks) is rethrown unchanged.
 */
export class S3MediaStore implements CampaignMediaStore {
  readonly kind = "s3" as const;
  constructor(
    private readonly client: S3Client,
    private readonly bucket: string,
    private readonly prefix: string,
    private readonly partBytes = DEFAULT_PART_BYTES,
  ) {
    if (partBytes < S3_MIN_PART_BYTES) throw new Error("S3 multipart parts must be at least 5 MiB");
  }

  private objectKey(key: string): string {
    assertMediaKey(key);
    return this.prefix ? `${this.prefix}/${key}` : key;
  }

  async put(key: string, body: AsyncIterable<Buffer>): Promise<void> {
    const Key = this.objectKey(key);
    const Bucket = this.bucket;
    let uploadId: string | undefined;
    const parts: Array<{ ETag: string; PartNumber: number }> = [];
    let buffered: Buffer[] = [];
    let bufferedBytes = 0;
    const sdk = async <T>(operation: string, run: () => Promise<T>): Promise<T> => {
      try {
        return await run();
      } catch (error) {
        throw unavailable(operation, error);
      }
    };
    const uploadPart = async (bytes: Buffer) => {
      if (!uploadId) {
        const created = await sdk("create_multipart", () => this.client.send(new CreateMultipartUploadCommand({ Bucket, Key, CacheControl: "private, no-store" })));
        if (!created.UploadId) throw unavailable("create_multipart", new Error("no upload id"));
        uploadId = created.UploadId;
      }
      const PartNumber = parts.length + 1;
      const id = uploadId;
      const result = await sdk("upload_part", () => this.client.send(new UploadPartCommand({ Bucket, Key, UploadId: id, PartNumber, Body: bytes, ContentLength: bytes.length })));
      if (!result.ETag) throw unavailable("upload_part", new Error("no etag"));
      parts.push({ ETag: result.ETag, PartNumber });
    };
    try {
      for await (const raw of body) {
        const chunk = Buffer.isBuffer(raw) ? raw : Buffer.from(raw);
        buffered.push(chunk);
        bufferedBytes += chunk.length;
        while (bufferedBytes >= this.partBytes) {
          const all = Buffer.concat(buffered);
          await uploadPart(all.subarray(0, this.partBytes));
          const rest = all.subarray(this.partBytes);
          buffered = rest.length ? [rest] : [];
          bufferedBytes = rest.length;
        }
      }
      const tail = Buffer.concat(buffered);
      if (!uploadId) {
        await sdk("put", () => this.client.send(new PutObjectCommand({ Bucket, Key, Body: tail, ContentLength: tail.length, CacheControl: "private, no-store" })));
        return;
      }
      if (tail.length) await uploadPart(tail);
      const id = uploadId;
      await sdk("complete_multipart", () => this.client.send(new CompleteMultipartUploadCommand({ Bucket, Key, UploadId: id, MultipartUpload: { Parts: parts } })));
    } catch (error) {
      if (uploadId) {
        const id = uploadId;
        await this.client.send(new AbortMultipartUploadCommand({ Bucket, Key, UploadId: id })).catch((abortError) => {
          logger.warn({ storage: "s3", operation: "abort_multipart", errorName: storageStatus(abortError).name }, "campaign media multipart abort failed");
        });
      }
      throw error;
    }
  }

  async read(key: string, maxBytes: number): Promise<Buffer> {
    const Key = this.objectKey(key);
    let response;
    try {
      response = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key }));
    } catch (error) {
      if (isMissing(error)) throw new CampaignMediaStoreError("not_found", "Stored campaign media was not found");
      throw unavailable("get", error);
    }
    const body = response.Body as Readable | undefined;
    if (!body) throw new CampaignMediaStoreError("unavailable", "Campaign media storage is unavailable");
    if ((response.ContentLength ?? 0) > maxBytes) {
      body.destroy();
      throw new CampaignMediaStoreError("too_large", TOO_LARGE);
    }
    const chunks: Buffer[] = [];
    let total = 0;
    try {
      for await (const chunk of body) {
        const piece = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk as Uint8Array);
        total += piece.length;
        if (total > maxBytes) {
          body.destroy();
          throw new CampaignMediaStoreError("too_large", TOO_LARGE);
        }
        chunks.push(piece);
      }
    } catch (error) {
      if (error instanceof CampaignMediaStoreError) throw error;
      throw unavailable("get_body", error);
    }
    return Buffer.concat(chunks);
  }

  /** Synchronous like the local store: the returned stream errors (before any data) if the object is missing. */
  stream(key: string): Readable {
    const Key = this.objectKey(key);
    const out = new PassThrough();
    void this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key })).then((response) => {
      const body = response.Body as Readable | undefined;
      if (out.destroyed) {
        body?.destroy();
        return;
      }
      if (!body) {
        out.destroy(new CampaignMediaStoreError("unavailable", "Campaign media storage is unavailable"));
        return;
      }
      // A client disconnect (the route destroys `out`) must also release the storage socket.
      out.once("close", () => body.destroy());
      body.once("error", () => out.destroy(new CampaignMediaStoreError("unavailable", "Campaign media storage is unavailable")));
      body.pipe(out);
    }, (error: unknown) => {
      out.destroy(isMissing(error)
        ? new CampaignMediaStoreError("not_found", "Stored campaign media was not found")
        : unavailable("get_stream", error));
    });
    return out;
  }

  async remove(key: string): Promise<void> {
    const Key = this.objectKey(key);
    try {
      await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key }));
    } catch (error) {
      if (isMissing(error)) return;
      throw unavailable("delete", error);
    }
  }
}

export type CampaignMediaStorageConfig =
  | { kind: "none" }
  | { kind: "local"; dir: string }
  | {
    kind: "s3";
    endpoint: string | undefined;
    region: string;
    bucket: string;
    prefix: string;
    forcePathStyle: boolean;
    accessKeyId: string;
    secretAccessKey: string;
  };

const S3_VARIABLES = [
  "CAMPAIGN_MEDIA_S3_ENDPOINT",
  "CAMPAIGN_MEDIA_S3_REGION",
  "CAMPAIGN_MEDIA_S3_BUCKET",
  "CAMPAIGN_MEDIA_S3_PREFIX",
  "CAMPAIGN_MEDIA_S3_FORCE_PATH_STYLE",
  "CAMPAIGN_MEDIA_S3_ACCESS_KEY_ID",
  "CAMPAIGN_MEDIA_S3_SECRET_ACCESS_KEY",
] as const;

function value(env: NodeJS.ProcessEnv, name: string): string | undefined {
  const raw = env[name]?.trim();
  return raw ? raw : undefined;
}

function parseEndpoint(raw: string | undefined): string | undefined {
  if (raw === undefined) return undefined;
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    throw new Error("CAMPAIGN_MEDIA_S3_ENDPOINT must be a full http(s) origin such as https://minio.internal:9000");
  }
  if ((url.protocol !== "http:" && url.protocol !== "https:") || url.username || url.password || /[?#]/.test(raw) || url.pathname !== "/") {
    throw new Error("CAMPAIGN_MEDIA_S3_ENDPOINT must be a full http(s) origin such as https://minio.internal:9000");
  }
  return url.origin;
}

/**
 * Strict parse of the media storage settings (pure; throws an Error naming the variable, never echoing a
 * secret). A half-configured server refuses to start rather than silently dropping uploads.
 */
export function parseCampaignMediaStorageConfig(env: NodeJS.ProcessEnv = process.env): CampaignMediaStorageConfig {
  const selector = value(env, "CAMPAIGN_MEDIA_STORAGE");
  const stray = [value(env, "CAMPAIGN_MEDIA_STORAGE_DIR") ? "CAMPAIGN_MEDIA_STORAGE_DIR" : null, ...S3_VARIABLES.filter((name) => value(env, name))].filter(Boolean);
  if (selector === undefined) {
    if (stray.length) throw new Error(`${stray[0]} is set but CAMPAIGN_MEDIA_STORAGE is not; set CAMPAIGN_MEDIA_STORAGE=local or s3`);
    return { kind: "none" };
  }
  if (selector === "local") {
    if (env.NODE_ENV === "production") throw new Error("CAMPAIGN_MEDIA_STORAGE=local is refused in production; use s3");
    const dir = value(env, "CAMPAIGN_MEDIA_STORAGE_DIR");
    if (!dir || !path.isAbsolute(dir)) throw new Error("CAMPAIGN_MEDIA_STORAGE=local needs CAMPAIGN_MEDIA_STORAGE_DIR set to an absolute directory");
    const s3Stray = S3_VARIABLES.find((name) => value(env, name));
    if (s3Stray) throw new Error(`${s3Stray} is set but CAMPAIGN_MEDIA_STORAGE=local`);
    return { kind: "local", dir };
  }
  if (selector !== "s3") throw new Error("CAMPAIGN_MEDIA_STORAGE must be local or s3");
  if (value(env, "CAMPAIGN_MEDIA_STORAGE_DIR")) throw new Error("CAMPAIGN_MEDIA_STORAGE_DIR is set but CAMPAIGN_MEDIA_STORAGE=s3");
  const endpoint = parseEndpoint(value(env, "CAMPAIGN_MEDIA_S3_ENDPOINT"));
  const region = value(env, "CAMPAIGN_MEDIA_S3_REGION") ?? "us-east-1";
  if (!/^[a-z0-9-]{1,32}$/.test(region)) throw new Error("CAMPAIGN_MEDIA_S3_REGION is not a valid region name");
  const bucket = value(env, "CAMPAIGN_MEDIA_S3_BUCKET");
  if (!bucket) throw new Error("CAMPAIGN_MEDIA_STORAGE=s3 needs CAMPAIGN_MEDIA_S3_BUCKET");
  if (!/^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$/.test(bucket)) throw new Error("CAMPAIGN_MEDIA_S3_BUCKET is not a valid bucket name");
  const prefixRaw = env.CAMPAIGN_MEDIA_S3_PREFIX === undefined ? "campaign-media" : env.CAMPAIGN_MEDIA_S3_PREFIX.trim();
  if (prefixRaw && !prefixRaw.split("/").every((segment) => /^[A-Za-z0-9._-]+$/.test(segment) && segment !== "." && segment !== "..")) {
    throw new Error("CAMPAIGN_MEDIA_S3_PREFIX must be path segments of letters, digits, dot, dash or underscore, without a leading or trailing slash");
  }
  const forcePathStyleRaw = value(env, "CAMPAIGN_MEDIA_S3_FORCE_PATH_STYLE");
  if (forcePathStyleRaw !== undefined && forcePathStyleRaw !== "true" && forcePathStyleRaw !== "false") {
    throw new Error("CAMPAIGN_MEDIA_S3_FORCE_PATH_STYLE must be true or false");
  }
  const forcePathStyle = forcePathStyleRaw === undefined ? endpoint !== undefined : forcePathStyleRaw === "true";
  const accessKeyId = value(env, "CAMPAIGN_MEDIA_S3_ACCESS_KEY_ID");
  if (!accessKeyId) throw new Error("CAMPAIGN_MEDIA_STORAGE=s3 needs CAMPAIGN_MEDIA_S3_ACCESS_KEY_ID");
  const secretAccessKey = value(env, "CAMPAIGN_MEDIA_S3_SECRET_ACCESS_KEY");
  if (!secretAccessKey) throw new Error("CAMPAIGN_MEDIA_STORAGE=s3 needs CAMPAIGN_MEDIA_S3_SECRET_ACCESS_KEY");
  return { kind: "s3", endpoint, region, bucket, prefix: prefixRaw, forcePathStyle, accessKeyId, secretAccessKey };
}

/** The parsed configuration without credentials, for the startup log. Throws on a malformed configuration. */
export function describeCampaignMediaStorage(env: NodeJS.ProcessEnv = process.env) {
  const config = parseCampaignMediaStorageConfig(env);
  if (config.kind === "s3") {
    return { kind: config.kind, endpoint: config.endpoint ?? "aws", region: config.region, bucket: config.bucket, prefix: config.prefix, forcePathStyle: config.forcePathStyle };
  }
  return { kind: config.kind };
}

/** A configured S3 client: explicit credentials only (never the default provider chain), checksums only when required. */
export function createS3Client(config: Extract<CampaignMediaStorageConfig, { kind: "s3" }>): S3Client {
  return new S3Client({
    region: config.region,
    endpoint: config.endpoint,
    forcePathStyle: config.forcePathStyle,
    credentials: { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey },
    requestChecksumCalculation: "WHEN_REQUIRED",
    responseChecksumValidation: "WHEN_REQUIRED",
    maxAttempts: 3,
    requestHandler: { connectionTimeout: 5_000, requestTimeout: 60_000 },
  });
}

let override: CampaignMediaStore | null | undefined;
let cached: { fingerprint: string; store: CampaignMediaStore | null } | undefined;

/** Tests only: install (or clear with undefined) a store. */
export function setCampaignMediaStoreForTests(store: CampaignMediaStore | null | undefined): void {
  override = store;
}

/** The configured store (one per configuration, so the S3 connection pool is reused), or null when none. */
export function configuredCampaignMediaStore(env: NodeJS.ProcessEnv = process.env): CampaignMediaStore | null {
  if (override !== undefined) return override;
  const fingerprint = JSON.stringify(["CAMPAIGN_MEDIA_STORAGE", "CAMPAIGN_MEDIA_STORAGE_DIR", "NODE_ENV", ...S3_VARIABLES].map((name) => env[name] ?? null));
  if (cached?.fingerprint === fingerprint) return cached.store;
  const config = parseCampaignMediaStorageConfig(env);
  const store = config.kind === "none" ? null
    : config.kind === "local" ? new LocalDiskMediaStore(config.dir)
      : new S3MediaStore(createS3Client(config), config.bucket, config.prefix);
  cached = { fingerprint, store };
  return store;
}
